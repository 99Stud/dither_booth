/**
 * Generates the 64x64 blue-noise threshold mask used by the "Blue noise
 * (macOS)" dither mode, with Ulichney's void-and-cluster method on a torus.
 *
 * macOS prints to the TM-T20III by thresholding 8-bit gray against a 64x64
 * dispersed-dot mask. We use the same kind of screen, but a mask generated
 * here rather than Apple's table.
 *
 * Run: bun scripts/generate-blue-noise-mask.ts
 */
import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const SIZE = 64;
const PIXELS = SIZE * SIZE;
const SIGMA = 1.5;
const INITIAL_DENSITY = 0.1;
const SEED = 0x9e3779b9;

const appRoot = resolve(dirname(Bun.fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(
  appRoot,
  "src/domains/image-manipulation/internal/blue-noise-mask.ts",
);

const mulberry32 = (seed: number) => {
  let state = seed >>> 0;

  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};

/** Gaussian weight for every toroidal offset, indexed by dy * SIZE + dx. */
const kernel = new Float64Array(PIXELS);
for (let dy = 0; dy < SIZE; dy++) {
  for (let dx = 0; dx < SIZE; dx++) {
    const wy = Math.min(dy, SIZE - dy);
    const wx = Math.min(dx, SIZE - dx);
    kernel[dy * SIZE + dx] = Math.exp(-(wx * wx + wy * wy) / (2 * SIGMA ** 2));
  }
}

class EnergyField {
  readonly bits = new Uint8Array(PIXELS);
  readonly energy = new Float64Array(PIXELS);

  static from(bits: Uint8Array) {
    const field = new EnergyField();
    for (let index = 0; index < PIXELS; index++) {
      if (bits[index]) field.set(index, 1);
    }
    return field;
  }

  set(index: number, value: 0 | 1) {
    if (this.bits[index] === value) return;
    this.bits[index] = value;

    const sign = value ? 1 : -1;
    const py = Math.floor(index / SIZE);
    const px = index % SIZE;

    for (let y = 0; y < SIZE; y++) {
      const kernelRow = ((y - py + SIZE) % SIZE) * SIZE;
      for (let x = 0; x < SIZE; x++) {
        this.energy[y * SIZE + x]! +=
          sign * kernel[kernelRow + ((x - px + SIZE) % SIZE)]!;
      }
    }
  }

  /** The set pixel with the most set neighbours. */
  tightestCluster() {
    let best = -1;
    for (let index = 0; index < PIXELS; index++) {
      if (
        this.bits[index] &&
        (best < 0 || this.energy[index]! > this.energy[best]!)
      ) {
        best = index;
      }
    }
    return best;
  }

  /** The unset pixel with the fewest set neighbours. */
  largestVoid() {
    let best = -1;
    for (let index = 0; index < PIXELS; index++) {
      if (
        !this.bits[index] &&
        (best < 0 || this.energy[index]! < this.energy[best]!)
      ) {
        best = index;
      }
    }
    return best;
  }
}

const random = mulberry32(SEED);
const initialOnes = Math.round(PIXELS * INITIAL_DENSITY);
const initial = new Uint8Array(PIXELS);
for (let placed = 0; placed < initialOnes;) {
  const index = Math.floor(random() * PIXELS);
  if (!initial[index]) {
    initial[index] = 1;
    placed++;
  }
}

// Spread the initial points until moving the tightest one no longer helps.
const prototype = EnergyField.from(initial);
for (;;) {
  const cluster = prototype.tightestCluster();
  prototype.set(cluster, 0);
  const voidIndex = prototype.largestVoid();
  prototype.set(voidIndex, 1);
  if (voidIndex === cluster) break;
}

const ranks = new Uint16Array(PIXELS);

// Ranks below the prototype: remove its tightest clusters one at a time.
const shrinking = EnergyField.from(prototype.bits);
for (let rank = initialOnes - 1; rank >= 0; rank--) {
  const cluster = shrinking.tightestCluster();
  shrinking.set(cluster, 0);
  ranks[cluster] = rank;
}

// Ranks above the prototype: fill its largest voids one at a time.
const growing = EnergyField.from(prototype.bits);
for (let rank = initialOnes; rank < PIXELS; rank++) {
  const voidIndex = growing.largestVoid();
  growing.set(voidIndex, 1);
  ranks[voidIndex] = rank;
}

const rows: string[] = [];
for (let y = 0; y < SIZE; y++) {
  rows.push(
    `  ${Array.from(ranks.subarray(y * SIZE, (y + 1) * SIZE)).join(", ")},`,
  );
}

await writeFile(
  outputPath,
  `// Generated by apps/engine/scripts/generate-blue-noise-mask.ts. Do not edit.

/**
 * 64x64 void-and-cluster blue-noise rank order (σ = ${SIGMA}, seed ${SEED}).
 * Each value 0..4095 appears once, row-major.
 */
export const BLUE_NOISE_MASK_SIZE = ${SIZE};

// prettier-ignore
export const BLUE_NOISE_MASK_RANKS = Uint16Array.from([
${rows.join("\n")}
]);
`,
);

console.log(`Wrote ${outputPath}`);
